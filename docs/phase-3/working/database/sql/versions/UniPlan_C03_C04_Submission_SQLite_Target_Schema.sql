-- UniPlan C-03/C-04: Versioned final-file submission receipts; no assignment grading.
-- This is the canonical target schema for a fresh database / reviewed schema update.
-- Back up any existing database and reconcile legacy rows before applying to a populated DB.

PRAGMA foreign_keys = ON;

-- Assignment brief fields relevant to final-file submissions.
-- Merge these columns into the canonical ASSIGNMENT definition.
-- allowed_file_types: comma-separated allowed extensions, validated against detected content in Flask.
-- allow_resubmission: 0 means one accepted version only; 1 permits later accepted versions.
CREATE TABLE IF NOT EXISTS ASSIGNMENT_V4 (
    assignment_id       INTEGER PRIMARY KEY,
    section_id          INTEGER NOT NULL,
    title               TEXT NOT NULL,
    description         TEXT,
    due_at              TEXT NOT NULL, -- ISO-8601 UTC
    created_by          INTEGER NOT NULL,
    allowed_file_types  TEXT NOT NULL,
    max_file_size_mb    INTEGER NOT NULL CHECK (max_file_size_mb > 0),
    allow_resubmission  INTEGER NOT NULL DEFAULT 0 CHECK (allow_resubmission IN (0,1)),
    FOREIGN KEY (section_id) REFERENCES SECTION(section_id),
    FOREIGN KEY (created_by) REFERENCES USER(user_id)
);

CREATE TABLE IF NOT EXISTS ASSIGNMENT_SUBMISSION_V4 (
    submission_id       INTEGER PRIMARY KEY,
    assignment_id       INTEGER NOT NULL,
    student_id          INTEGER NOT NULL,
    version_number      INTEGER NOT NULL CHECK (version_number > 0),
    file_path           TEXT NOT NULL,
    original_filename   TEXT NOT NULL,
    file_size_bytes     INTEGER NOT NULL CHECK (file_size_bytes > 0),
    mime_type           TEXT NOT NULL,
    submitted_at        TEXT NOT NULL, -- generated by server in ISO-8601 UTC
    receipt_code        TEXT NOT NULL UNIQUE,
    receipt_status      TEXT NOT NULL DEFAULT 'RECEIVED' CHECK (receipt_status = 'RECEIVED'),
    CONSTRAINT uq_submission_version UNIQUE (assignment_id, student_id, version_number),
    FOREIGN KEY (assignment_id) REFERENCES ASSIGNMENT_V4(assignment_id),
    FOREIGN KEY (student_id) REFERENCES STUDENT_PROFILE(user_id)
);

CREATE INDEX IF NOT EXISTS ix_submission_student_assignment
    ON ASSIGNMENT_SUBMISSION_V4(student_id, assignment_id, version_number DESC);

-- Prevent versions beyond 1 when resubmission is disabled.
CREATE TRIGGER IF NOT EXISTS trg_submission_resubmission_policy
BEFORE INSERT ON ASSIGNMENT_SUBMISSION_V4
FOR EACH ROW
WHEN NEW.version_number > 1
 AND COALESCE((SELECT allow_resubmission FROM ASSIGNMENT_V4 WHERE assignment_id = NEW.assignment_id), 0) = 0
BEGIN
    SELECT RAISE(ABORT, 'Resubmission is not allowed for this assignment');
END;

-- Enforce sequential version numbering and prevent gaps.
CREATE TRIGGER IF NOT EXISTS trg_submission_next_version
BEFORE INSERT ON ASSIGNMENT_SUBMISSION_V4
FOR EACH ROW
WHEN NEW.version_number <> COALESCE(
    (SELECT MAX(version_number) + 1
       FROM ASSIGNMENT_SUBMISSION_V4
      WHERE assignment_id = NEW.assignment_id AND student_id = NEW.student_id),
    1
)
BEGIN
    SELECT RAISE(ABORT, 'Submission version must be the next sequential version');
END;

-- Accepted submission versions are immutable. Create a new row for resubmission.
CREATE TRIGGER IF NOT EXISTS trg_submission_immutable
BEFORE UPDATE ON ASSIGNMENT_SUBMISSION_V4
FOR EACH ROW
BEGIN
    SELECT RAISE(ABORT, 'Accepted submission versions are immutable; insert a new version instead');
END;

-- Service-layer transaction outline (pseudocode):
-- 1. Authenticate user and check that the assignment belongs to a relevant course.
-- 2. Check deadline/window, file type/content, size, and allow_resubmission policy.
-- 3. Compute next_version = COALESCE(MAX(version_number)+1, 1) inside a transaction.
-- 4. Save file bytes to local storage using a safe generated name; never trust the client path.
-- 5. Insert file metadata + server timestamp + unique receipt_code.
-- 6. Commit. If DB insert/commit fails, remove the newly saved file to avoid an orphan.
-- 7. Return receipt details. Never create a success receipt on validation failure.

